// The kind of transaction is sometimes enough on its own
const KIND_DEFAULTS: Partial<Record<SmsKind, string>> = {
  recharge: "communication:mobile-data",
  cash_out: "finance:cash-withdrawal",
};

export function defaultCategoryFor(merchantKey: string | null, kind: SmsKind): string | null {
  if (merchantKey) {
    // Whole-word match ("robi" must not hit "robintex"). Multi-word keywords
    // also match glued together ("startech" for "star tech").
    const padded = ` ${merchantKey} `;
    const compact = ` ${merchantKey.replace(/\s/g, "")}`;
    for (const [keyword, category] of DEFAULT_MERCHANTS) {
      const glued = keyword.includes(" ") && compact.includes(` ${keyword.replace(/\s/g, "")}`);
      if (padded.includes(` ${keyword} `) || glued) {
        return category;
      }
    }
  }
  return KIND_DEFAULTS[kind] ?? null;
}
